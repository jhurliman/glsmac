#!/usr/bin/env python3
"""Project owned text and literal original outputs; never execute research code."""
import argparse
import hashlib
import json
from pathlib import Path

FIXTURE_SHA256 = "65fe760ee3c87687663e4d3e297533342fe804e35001a6a294761ef62bddfea6"


def project(source):
    raw = source.read_bytes()
    if hashlib.sha256(raw).hexdigest() != FIXTURE_SHA256:
        raise ValueError("Unexpected RE-SMAC-BASE-TEXT-001 fixture")
    cases = json.loads(raw)["cases"]
    assert len(cases) == 38
    out = ["// Generated by tools/reference/project_resourceinfo_cases.py.",
           "// Literal owned inputs/outputs from RE-SMAC-BASE-TEXT-001; no installed text.",
           "// Input SHA256: " + FIXTURE_SHA256, "#pragma once", "",
           "namespace gse::tests::resource_text_fixture {",
           "using game::backend::resource::smac::RuleTriple; using game::backend::resource::smac::Yield;",
           "struct Case { const char* id; const char* text; std::array< RuleTriple, 3 > rules; std::array< Yield, 16 > yields; };",
           "inline const Case cases[] = {"]
    count = 0
    for case in cases:
        if case.get("synthetic_text") is None:
            assert case["id"] == "installed"
            continue
        expected_order = [(resource, tanks, dome) for resource in ("none", "nutrient", "mineral", "energy")
                          for tanks, dome in ((False, False), (True, False), (False, True), (True, True))]
        assert [(c["resource"], c["tanks"], c["dome"]) for c in case["checks"]] == expected_order
        rules = [case["expected_rows"][i][:3] for i in (1, 2, 4)]
        triple = lambda name, values: name + "{ " + ", ".join(map(str, values)) + " }"
        out += ["\t{ " + json.dumps(case["id"]) + ", " + json.dumps(case["synthetic_text"]) + ",",
                "\t\t{ " + ", ".join(triple("RuleTriple", row) for row in rules) + " },",
                "\t\t{ " + ", ".join(triple("Yield", c["expected"]) for c in case["checks"]) + " } },"]
        count += 1
    assert count == 37
    return "\n".join(out + ["};", "}", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("fixture", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.write_text(project(args.fixture), encoding="utf-8", newline="\n")
