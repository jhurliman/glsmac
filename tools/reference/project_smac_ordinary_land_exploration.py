#!/usr/bin/env python3
"""Project pinned public semantic captures; never execute/model exploration."""
import argparse
import hashlib
import json
from pathlib import Path

PINS = {
    "placements": "20065782ed34d701f978fd6fb9711f2a80590bfc3691e2a58fd0933992d8d68c",
    "transitions": "757a9fa95819724d19c09c49501afcbeb8a8e37b76ebd7af1f1e710045b60a78",
}


def read(path, key):
    raw = path.read_bytes()
    if hashlib.sha256(raw).hexdigest() != PINS[key]:
        raise ValueError(f"{key} source hash differs")
    return json.loads(raw)


def coordinate(value):
    x, y = value
    if not (0 <= x < 64 and 0 <= y < 32 and x % 2 == y % 2):
        raise ValueError("invalid captured coordinate")
    return f"{{ {x}, {y} }}"


def coordinates(values):
    if len(set(map(tuple, values))) != len(values):
        raise ValueError("duplicate captured set coordinate")
    return "{ " + ", ".join(map(coordinate, values)) + " }"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--placements", type=Path, required=True)
    parser.add_argument("--transitions", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    placements = read(args.placements, "placements")
    transitions = read(args.transitions, "transitions")
    if (placements["world_width"], placements["world_height"], placements["actor_faction"]) != (64, 32, 1):
        raise ValueError("capture geometry/actor changed")
    if len(placements["cases"]) != 194 or len(transitions["cases"]) != 7:
        raise ValueError("capture count changed")
    lines = [
        "// Generated by project_smac_ordinary_land_exploration.py from public semantic values.",
        "// Placement SHA256: " + PINS["placements"],
        "// Transition SHA256: " + PINS["transitions"],
        "// 194 fresh factory captures; 14 earlier continuous movement/factory transitions.",
        "// Expected coordinate lists are sets, not callback traversal order.",
        "#pragma once", "#include <array>", "#include <vector>",
        '#include "game/backend/map/SmacOrdinaryLandExploration.h"',
        "namespace gse::tests::fixtures::smac_exploration {",
        "using Coordinate = game::backend::map::smac_exploration::Coordinate;",
        "struct Placement { const char* name; bool coast; Coordinate center; bool wrap; uint8_t other_mask;",
        "    std::vector< Coordinate > initial, expected, refreshed; };",
        "inline const std::array< Placement, 194 > PLACEMENTS = {{",
    ]
    for c in placements["cases"]:
        if c["terrain"] not in ("flat", "rolling", "rocky", "forest", "fungus", "coast"):
            raise ValueError("unsupported capture terrain")
        others = c["other_exploration_factions"]
        if any(f not in range(2, 8) for f in others) or len(set(others)) != len(others):
            raise ValueError("invalid preservation factions")
        mask = sum(1 << f for f in others)
        lines.append("    { " + ", ".join([
            json.dumps(c["id"]), str(c["terrain"] == "coast").lower(), coordinate(c["coordinate"]),
            str(c["horizontal_wrap"]).lower(), str(mask), coordinates(c["initial_explored"]),
            coordinates(c["expected_explored"]), coordinates(c["expected_refreshed_improvement_memory"]),
        ]) + " },")
    lines += ["}};", "struct Step { Coordinate center; std::vector< Coordinate > expected; };",
              "struct Transition { const char* faction; std::vector< Coordinate > initial; std::array< Step, 2 > steps; };",
              "inline const std::array< Transition, 7 > TRANSITIONS = {{"]
    for c in transitions["cases"]:
        if [s["operation"] for s in c["steps"]] != ["owned_unit_east_move", "colony_factory"]:
            raise ValueError("transition operations changed")
        steps = ", ".join("{ " + coordinate(s["coordinate"]) + ", " + coordinates(s["expected_explored"]) + " }" for s in c["steps"])
        lines.append("    { " + json.dumps(c["source_faction"]) + ", " + coordinates(c["initial_explored"]) + ", {{ " + steps + " }} },")
    lines += ["}};", "}", ""]
    args.output.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("Projected 194 placements and 14 retained transitions; expected sets copied without simulation.")


if __name__ == "__main__":
    main()
