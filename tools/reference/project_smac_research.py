#!/usr/bin/env python3
"""Project literal public research captures; no expected arithmetic is recomputed."""
import argparse
import hashlib
import json
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument("behavior", type=Path)
parser.add_argument("output", type=Path)
args = parser.parse_args()
names = ["research-costs-and-cache-cases.json", "research-picker-pool-cases.json", "research-start-inputs-cases.json"]
data = {}
lines = ["// Generated by tools/reference/project_smac_research.py; literal original captures."]
for name in names:
    raw = (args.behavior / name).read_bytes()
    lines.append(f"// {name} SHA256 {hashlib.sha256(raw).hexdigest()}")
    data[name] = json.loads(raw)
lines += ["#pragma once", "namespace gse::tests::research_fixture {", "inline std::string Costs() {"]
costs = 0
for case in data[names[0]]["cases"]:
    if case["kind"] != "query":
        continue
    v = case["inputs"]
    lines += ["{ game::backend::faction::SmacResearchCostInputs input{};"]
    fields = {"score":"technology_score", "discount":"discount_buffer", "deferred":"deferred_awards", "human":"human", "owner_difficulty":"faction_difficulty", "global_difficulty":"global_difficulty", "turn":"turn", "intrinsic_research":"intrinsic_research", "discovery_rate":"discovery_rate", "technology_cost_percent":"techcost_percent", "map_width":"map_width", "map_height":"map_height", "stagnation":"tech_stagnation", "cache":"cache"}
    for field, key in fields.items():
        lines.append(f"input.{field}={json.dumps(v[key])};")
    for owner, values in v["other_factions"].items():
        lines.append(f"input.other_scores[{int(owner)-1}]={values.get('technology_score',0)}; input.other_deferred[{int(owner)-1}]={values.get('deferred_awards',0)};")
    lines.append(f'if(game::backend::faction::CalculateSmacResearchCost(input)!={case["expected"]["cost"]}) {{return "{case["id"]}";}} }}')
    costs += 1
lines += ['return {}; }', 'inline std::string Pools() {']
pools = 0
for case in data[names[1]]["cases"]:
    v = case["inputs"]
    if v["mode"] != 0 or v["source"] >= 0 or v["faction"] == 0:
        continue
    lines += ['{ auto catalog=smac_rules_fixture::Technologies();', 'for(auto& row:catalog.technologies) {row.prerequisites={"Disable","Disable"};row.priorities={0,0,0,1};}', f'game::backend::faction::SmacFactionTechnologyState owner{{{{{v["faction"]},"GAIANS"}}}}; owner.score={v["score"]};']
    for ident, row in v["definitions"].items():
        tokens = ['None' if n == -1 else 'Disable' if n == -2 else f'Tech{n}' for n in row["prerequisites"]]
        lines.append(f'catalog.technologies[{ident}].prerequisites={{{json.dumps(tokens[0])},{json.dumps(tokens[1])}}}; catalog.technologies[{ident}].priorities={{{",".join(map(str,row["ratings"]))}}};')
    for ident in v["owners"].get(str(v["faction"]), []):
        lines.append(f"owner.owned[{ident}]=true;")
    expected = ','.join(map(str, case['expected_offered_technologies']))
    lines.append(f'if(game::backend::faction::SmacManualResearchPool(owner,catalog)!=std::vector<int32_t>{{{expected}}}) {{return "{case["id"]}";}} }}')
    pools += 1
lines += ['return {}; }', 'struct Rate {const char* token; int32_t expected;};', 'inline const Rate rates[]{']
for case in data[names[2]]["lexical_cases"]:
    lines.append(f'{{{json.dumps(case["token"])},{case["discovery_rate_percent"]}}},')
lines += ['};', f'// {costs} direct costs; {pools} ordinary positive-owner option0 pools; {len(data[names[2]]["lexical_cases"])} rate tokens.', '}']
args.output.write_bytes(('\n'.join(lines)+'\n').encode('utf-8'))
print(costs, pools, len(data[names[2]]["lexical_cases"]))
