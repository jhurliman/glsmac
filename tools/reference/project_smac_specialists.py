#!/usr/bin/env python3
"""Project literal original specialist results; never calculate expected outputs."""
import argparse
import hashlib
import json
from pathlib import Path

PINS = {
    "manual-specialist-menu-cases.json": "81497122828840b077fca52640e59f289e21b8854ef59a8b6e3893e085bd093e",
    "specialist-replacement-and-overflow-cases.json": "985c6f10bd3dcb83f852043ccafbed0ef38f720f27fd7838a1fdffe9e0e473d4",
}
NAMES = ["technician", "doctor", "librarian", "engineer", "empath", "thinker", "transcend"]
TECHS = ["PlaNets", "Fusion", "CentMed", "MindMac", "AlphCen"]


def project(root):
    data = {}
    for name, pin in PINS.items():
        raw = (root / name).read_bytes()
        if hashlib.sha256(raw).hexdigest() != pin:
            raise ValueError(f"source fingerprint mismatch: {name}")
        data[name] = json.loads(raw)
    lines = ["#pragma once", "// Generated by tools/reference/project_smac_specialists.py from pinned original cases.",
             "namespace gse::tests::smac_specialist_fixture {",
             "struct MenuCase { const char* id; uint32_t population; int32_t minimum; int current; uint8_t available, obsolete; std::array<int32_t,7> psych; uint8_t expected; bool explanation; };",
             "inline const MenuCase menus[] = {"]
    menu = data["manual-specialist-menu-cases.json"]
    for case in menu["cases"]:
        value = menu["defaults"] | case["overrides"]
        psych = [0, 2, 0, 0, 2, 1, 2]
        for name, amount in value["psych_overrides"].items():
            psych[NAMES.index(name.lower())] = amount
        mask = lambda values: sum(1 << i for i, enabled in enumerate(values) if enabled)
        current = value["current_type"].lower()
        expected = sum(1 << NAMES.index(name.lower()) for name in case["expected"]["eligible_types"])
        lines.append("\t{ %s, %d, %d, %d, %d, %d, { %s }, %d, %s }," %
                     (json.dumps(case["id"]), value["population"], value["minimum_specialist_size"],
                      -1 if current == "worker" else NAMES.index(current), mask(value["available"]),
                      mask(value["obsolete"]), ", ".join(map(str, psych)), expected,
                      str(case["expected"]["size_explanation_requested"]).lower()))
    lines += ["};", "struct AutomaticCase { const char* id; uint32_t population; int32_t minimum; uint8_t known, expected; size_t repetitions; };",
              "inline const AutomaticCase automatic[] = {"]
    source = data["specialist-replacement-and-overflow-cases.json"]
    for case in source["cases"]:
        choices = case["expected"]["overflow_initial_choices"]
        if not choices:
            continue
        value = source["defaults"] | case["overrides"]
        if value["output_overrides"] or len(set(choices)) != 1:
            raise ValueError("projection requires explicit output override/repeated-choice handling")
        known = sum(1 << TECHS.index(name) for name in value["known_technologies"])
        lines.append("\t{ %s, %d, %d, %d, %d, %d }," % (json.dumps(case["id"]), value["population"],
                     value["minimum_specialist_size"], known, NAMES.index(choices[0]), len(choices)))
    return "\n".join(lines + ["};", "}", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="read-only directory containing the two pinned JSON files")
    parser.add_argument("output", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = project(args.source)
    if args.check:
        if args.output.read_text() != result:
            raise SystemExit("owned projection differs")
        print("14 menu cases and 6 automatic contexts match pinned literal outputs")
    else:
        args.output.write_text(result, newline="\n")


if __name__ == "__main__":
    main()
