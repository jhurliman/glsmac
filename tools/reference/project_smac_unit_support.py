"""Project pinned original support outputs; no emulator or support formula."""
import argparse
import hashlib
import json
from pathlib import Path

FIXTURE_SHA = "7b14abc88b0c41393111cb41b5ee6a1da6da18306feae416d11c4ff70087ddec"
REPORT_SHA = "b96988121be0a122537ee6d70d972986fc9afe75b6bec04ae65a14a4ac4f440b"
EXE_SHA = "0a61eb3642df750c0d5e516c3e3efeb4ad5ae7e1ce3163617759449327952a01"


def require(condition, message):
    if not condition:
        raise ValueError(message)


def read(path, expected):
    data = Path(path).read_bytes()
    require(hashlib.sha256(data).hexdigest() == expected, f"Evidence hash mismatch: {path}")
    return json.loads(data)


def project(fixture, report):
    require(fixture["reference_sha256"] == report["executable_sha256"] == EXE_SHA, "Executable identity differs")
    require(report["fixtures_sha256"] == FIXTURE_SHA, "Report fixture identity differs")
    require(not report["negative_control_guest_memory_mutation"], "Negative control is not reference evidence")
    require(report["passed"] == report["total"] == 37, "Original cases did not all pass")
    require([c["id"] for c in report["cases"]] == [c["id"] for c in fixture["cases"]], "Ordered case identities differ")
    out = ["// Generated by project_smac_unit_support.py from pinned literal original outputs.",
           "#pragma once", "#include <array>", '#include "game/backend/base/SmacUnitSupport.h"',
           "namespace gse::tests::smac_support_fixture {",
           "using namespace game::backend::base;",
           "struct Case { const char* id; int32_t rating, population; std::size_t count;",
           "    std::array<SmacSupportUnit,7> units; int32_t cost, eligible; uint32_t paid_mask;",
           "    int32_t clean_index, clean_cost; };", "inline const Case cases[] = {"]
    package = dict(combat="Combat", colony="Colony", terraformer="Former", transport="Transport",
                   supply="Supply", probe="Probe", artifact="Artifact")
    home = dict(none="None", other="OtherBase", current="EvaluatingBase")
    terrain = dict(land="Land", shelf="Shelf", deep_ocean="DeepOcean", trench="Trench")
    count = transitions = 0
    boolean = lambda value: "true" if value else "false"
    for case, captured in zip(fixture["cases"], report["cases"]):
        if case["kind"] != "support":
            continue
        count += 1
        require(case["id"] == f"SUP-{count:03d}", "Support case sequence differs")
        require(captured["passed"] and captured["actual"] == case["expected"] == captured["expected"], f"Original output differs: {case['id']}")
        actual = captured["actual"]
        names = [unit["id"] for unit in case["units"]]
        require(len(set(names)) == len(names) <= 7, "Unit identities are duplicated or exceed fixture capacity")
        require(len(set(actual["paid_units"])) == len(actual["paid_units"]), "Paid unit identities are duplicated")
        paid = sum(1 << names.index(name) for name in actual["paid_units"])
        clean_index, clean_cost = -1, -1
        changes = captured["transition_checks"]
        require(len(changes) <= 1, "Unexpected transition count")
        if changes:
            change = changes[0]
            require(change["change"] == "give a previously paid unit Clean Reactor and recompute", "Unexpected transition kind")
            require(change["unit"] in actual["paid_units"] and change["cost_before"] == actual["cost"], "Clean transition input differs")
            require(change["paid_flag_cleared"] is True, "Clean transition retained its paid flag")
            clean_index, clean_cost = names.index(change["unit"]), change["cost_after"]
            transitions += 1
        out.append(f'    {{"{case["id"]}",{case.get("support_rating", fixture["defaults"]["support_rating"])},'
                   f'{case.get("population", fixture["defaults"]["population"])},{len(names)},{{{{')
        for index, raw in enumerate(case["units"]):
            unit = fixture["defaults"]["unit"] | raw
            # Local ordinal IDs preserve correspondence only; never imply age.
            out.append(f'        {{{index+1},{boolean(unit["owned_by_faction"])},SmacSupportHome::{home[unit["home"]]},'
                       f'SmacSupportPackage::{package[unit["package"]]},{boolean(unit["clean_reactor"])},'
                       f'SmacSupportDesign::{"BuiltIn" if unit["builtin_design"] else "PlayerDesigned"},'
                       f'{boolean(unit["psi_weapon"])},{boolean(unit["fungus"])},SmacSupportTerrain::{terrain[unit["terrain_band"]]}}},')
        out.append(f'    }}}},{actual["cost"]},{actual["eligible"]},{paid}u,{clean_index},{clean_cost}}},')
    require(count == 28, "Support case count differs")
    out += ["};", "}", ""]
    return "\n".join(out), dict(support_cases=count, clean_transitions=transitions, excluded_cases=9)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fixture", required=True)
    parser.add_argument("--report", required=True)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()
    output, summary = project(read(args.fixture, FIXTURE_SHA), read(args.report, REPORT_SHA))
    Path(args.output).write_bytes(output.encode("utf-8"))
    print(json.dumps(summary | {"output_sha256": hashlib.sha256(output.encode()).hexdigest()}))
